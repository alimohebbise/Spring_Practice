package com.example.demo.Controller;

public class UserForm {

    private String name;
    private int age;

    public UserForm() {

    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    public int getAge() {
        return age;
    }

    public void setAge(int age) {
        this.age = age;
    }
}
